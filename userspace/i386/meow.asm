; ---------------------------------------------------------------------------
; A bootable cat, and a melody played on the 8254.
;
; This is an original sector written for this machine -- not the MEMZ payload.
; It exists because it is the smallest program that exercises the two things a
; music-playing boot sector needs and nothing else:
;
;   * PIT channel 2 as a square-wave generator. Channel 0 ticks the machine,
;     channel 1 refreshes DRAM, and channel 2 has no job at all: its output
;     goes to a gate on port 0x61, and a speaker sits behind the gate. Write a
;     divisor and close the gate and you hear that divisor; nothing else in the
;     machine has to care.
;
;   * the BIOS tick counter at 0x40:0x6C as a clock. The sector never reads the
;     PIT to time itself; it idles in hlt and lets IRQ0 advance the counter,
;     which is how every DOS program kept time.
;
; The tune is generated by the PIT, so there is no sample, no asset and no
; sound hardware beyond a device that toggles a pin.
; ---------------------------------------------------------------------------

[bits 16]
org 0x7C00

TICKS   equ 0x046C                  ; the BIOS tick counter, 18.2 Hz
PIT_HZ  equ 1193182                 ; the 8254's input clock

start:
    cli
    xor     ax, ax
    mov     ds, ax
    mov     es, ax
    mov     ss, ax
    mov     sp, 0x7C00
    cld
    sti

    mov     ax, 0x0003              ; 80x25 colour text
    int     0x10
    mov     ah, 0x01                ; hide the cursor
    mov     cx, 0x0607
    int     0x10

    mov     si, msg_title
    call    puts

    xor     bp, bp                  ; bp = which note of the tune we are on
.again:
    call    draw_frame

    mov     si, tune
    add     si, bp                  ; two bytes a note
    lodsw                           ; ax = divisor, 0 ends the tune
    or      ax, ax
    jnz     .note
    xor     bp, bp                  ; round again
    jmp     .again
.note:
    push    ax
    call    play                   ; ax = divisor
    pop     ax
    push    ax
    call    show_hz
    mov     cx, 2                   ; two ticks a note, about 110 ms
    call    wait_ticks
    pop     ax
    call    silence
    add     bp, 2
    jmp     .again

; ---- drawing -------------------------------------------------------------

draw_frame:
    push    si
    push    bx
    mov     bx, [frame]
    and     bx, 3                   ; four frames: blink, blink, wide, meow
    add     bx, bx
    mov     si, [frames + bx]
    mov     dx, 0x0618              ; row 6, column 24
    call    draw3
    inc     word [frame]
    pop     bx
    pop     si
    ret

; si -> three zero-terminated lines, dx = row/column of the first
draw3:
    mov     cx, 3
.line:
    push    cx
    mov     ah, 0x02                ; set cursor
    xor     bh, bh
    int     0x10
    call    puts                    ; leaves si on this line's terminator
    inc     dh                      ; next row
    pop     cx
    loop    .line
    ret

puts:
    push    ax
    push    bx
.next:
    lodsb
    or      al, al
    jz      .done
    mov     ah, 0x0E
    xor     bx, bx
    int     0x10
    jmp     .next
.done:
    pop     bx
    pop     ax
    ret

; ---- sound ---------------------------------------------------------------

; ax = PIT divisor for channel 2, then close the speaker gate
play:
    push    ax
    mov     al, 0xB6                ; ch2, lo then hi, mode 3 square, binary
    out     0x43, al
    pop     ax
    out     0x42, al
    mov     al, ah
    out     0x42, al
    in      al, 0x61                ; bit 0 gates timer 2, bit 1 the speaker
    or      al, 3
    out     0x61, al
    ret

silence:
    push    ax
    in      al, 0x61
    and     al, 0xFC
    out     0x61, al
    pop     ax
    ret

; ax = divisor; print the frequency it makes, at row 11 column 24
show_hz:
    push    ax
    push    bx
    push    dx
    push    si
    mov     dx, 0x0B18
    mov     ah, 0x02
    xor     bh, bh
    int     0x10
    mov     si, msg_hz
    call    puts
    pop     si
    pop     dx
    pop     bx
    pop     ax
    mov     bx, ax                  ; divisor
    mov     cx, bx
    shr     cx, 1                   ; half a divisor, so the readout rounds
    mov     dx, PIT_HZ / 65536      ; 32-bit dividend, 16-bit divisor
    mov     ax, PIT_HZ % 65536
    add     ax, cx
    adc     dx, 0
    div     bx                      ; ax = what the gate will sound like
    call    put_dec
    mov     si, msg_hz_tail
    jmp     puts

put_dec:                            ; ax = number, no leading zeros
    push    ax
    push    bx
    push    cx
    push    dx
    mov     bx, 10
    xor     cx, cx
.digit:
    xor     dx, dx
    div     bx
    push    dx
    inc     cx
    or      ax, ax
    jnz     .digit
.out:
    pop     ax
    add     al, '0'
    mov     ah, 0x0E
    xor     bx, bx
    int     0x10
    loop    .out
    pop     dx
    pop     cx
    pop     bx
    pop     ax
    ret

; ---- the clock -----------------------------------------------------------

; cx = how many ticks to idle for. IRQ0 advances the counter; we only wait.
wait_ticks:
    push    ax
    push    bx
    mov     bx, [TICKS]
.wait:
    hlt
    mov     ax, [TICKS]
    sub     ax, bx
    cmp     ax, cx
    jb      .wait
    pop     bx
    pop     ax
    ret

; ---- data ----------------------------------------------------------------

msg_title:  db "MEOW-OS 1.0  (PIT channel 2 square wave)", 13, 10, 0
msg_hz:     db "PIT ch2 ", 0
msg_hz_tail: db " Hz  ", 0
; the tune: divisor for each note, terminated by a zero. C5 E5 G5 E5 A4 G5 C5
tune:       dw 2281, 1811, 1522, 1811, 2712, 1522, 2281, 0
frame:      dw 0

cat_0:      db "   /\_/\   ", 0
            db "  ( o.o )  ", 0
            db "   > ^ <   ", 0
cat_1:      db "   /\_/\   ", 0
            db "  ( -.- )  ", 0
            db "   > ^ <   ", 0
cat_2:      db "   /\_/\   ", 0
            db "  ( O.O )  ", 0
            db "   > w <   ", 0
cat_3:      db "   /\_/\   ", 0
            db "  ( o.o )  ", 0
            db "   > ^ <   ", 0

frames:     dw cat_0, cat_1, cat_2, cat_3

times 510 - ($ - $$) db 0
dw 0xAA55
