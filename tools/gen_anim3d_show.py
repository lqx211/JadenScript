PAIRS = {"{": "}", "[": "]", "(": ")"}


def match_bracket(text: str, start: int) -> int:
    opener = text[start]
    closer = PAIRS[opener]
    depth = 0
    i = start
    quote = None
    while i < len(text):
        c = text[i]
        if quote:
            if c == "\\":
                i += 2
                continue
            if c == quote:
                quote = None
        elif c in "\"'`":
            quote = c
        elif c in PAIRS:
            depth += 1
        elif c in PAIRS.values():
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return -1


def read_chapters() -> list[dict]:
    chapters = []
    for f in sorted((EXAMPLE / "src" / "ch").glob("[0-9][0-9]_*.js")):
        text = f.read_text()
        m = re.search(r"\bchapter\(\{", text)
        if not m:
            continue
        b = m.end() - 1
        body = text[b : match_bracket(text, b) + 1]
        cid = re.search(r'\bid: "([^"]+)"', body)
        shots = []
        sm = re.search(r"\n\tshots: \[", body)
        if sm:
            sb = sm.end() - 1
            sbody = body[sb : match_bracket(body, sb) + 1]
            for mm in re.finditer(r"^\t\t\{\s*$", sbody, re.M):
                ob = mm.end() - 1
                obj = sbody[ob : match_bracket(sbody, ob) + 1]
                sid = re.search(r'\bid: "([^"]+)"', obj)
                at = re.search(r"\bat: ([^\n]+),", obj)
                # The film labels most shots with `overlays(ctx, K, {br: "..."})`;
                # that bottom-right string is the caption the viewer reads.
                cap = ""
                for c in re.findall(r'\bbr:\s*"((?:[^"\\]|\\.)*)"', obj):
                    if c.strip():
                        cap = c
                        break
                shots.append(
                    {
                        "id": sid.group(1) if sid else None,
                        "at": at.group(1).strip() if at else None,
                        "cap": cap,
                    }
                )
        if shots:
            chapters.append(
                {
                    "id": cid.group(1) if cid else f.stem,
                    "shots": shots,
                    "keys": chapter_keys(text),
                }
            )
    return chapters


def grid_time(grid: list[float], x: float) -> float:
    """Fractional index in a rising time grid -> time, extrapolated past the ends."""
    n = len(grid)
    if n < 2:
        return 0.0
    if x <= 0:
        return grid[0] + x * (grid[1] - grid[0])
    if x >= n - 1:
        return grid[-1] + (x - (n - 1)) * (grid[-1] - grid[-2])
    i = int(x)
    return grid[i] + (x - i) * (grid[i + 1] - grid[i])


_CONST = re.compile(r"\(T\) => ([\d.]+)$")
# `keys(T).<sym>` with an optional `.start` / `.end` / `.words[k].start` tail.
_KEY_REF = re.compile(r"keys\(\w*\)\.(\w+)((?:\.\w+|\[\d+\]|\(\d+(?:\.\d+)?\))*)")
_LYRIC_ASSIGN = re.compile(r"\b(l\d+)\s*=\s*L\(\"([^\"]*)\"\)")
_KEYS_BODY = re.compile(r"return KC = \{(.*?)\n\t\};", re.S)
_MAP_ENTRY = re.compile(r"(\w+)\s*:\s*([^,\n}]+)")


def beat_index(beats: list[float], seconds: float) -> float:
    """Fractional index of ``seconds`` in the beat grid (the inverse of `grid_time`)."""
    n = len(beats)
    if n < 2:
        return 0.0
    if seconds <= beats[0]:
        return (seconds - beats[0]) / (beats[1] - beats[0])
    if seconds >= beats[-1]:
        return (n - 1) + (seconds - beats[-1]) / (beats[-1] - beats[-2])
    lo, hi = 0, n - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if beats[mid] <= seconds:
            lo = mid
        else:
            hi = mid
    return lo + (seconds - beats[lo]) / (beats[lo + 1] - beats[lo])


def chapter_keys(text: str) -> dict[str, tuple[str, object]]:
    """``symbol -> ('line', text)`` / ``('expr', source)`` from one chapter's `keys()`.

    Every chapter builds its timeline in a `keys(T)` helper; a shot's `at` reads
    a symbol out of it. Parsing the helper is the only way to know that
    ``keys(T).l29.start`` is 53.562 s short of evaluating the film.
    """
    table: dict[str, tuple[str, object]] = {}
    for m in _LYRIC_ASSIGN.finditer(text):
        table[m.group(1)] = ("line", m.group(2))
    bm = _KEYS_BODY.search(text)
    body = bm.group(1) if bm else text
    for m in _MAP_ENTRY.finditer(body):
        name, expr = m.group(1), m.group(2).strip()
        if not name.startswith("l"):
            table.setdefault(name, ("expr", expr))
    return table


def _find_line(lyrics: list[dict], want: str) -> dict | None:
    """The line `T.findLine(text)` returns: substring, smart case, first hit.

    Mirrors `src/engine/timing.js` exactly -- a lower-case query matches any
    case, a query with a capital matches as typed, and the *first* match in
    document order wins (the film does not prefer the current section).
    """
    exact = want != want.lower()
    q = want if exact else want.lower()
    for line in lyrics:
        text = line["text"] if exact else line["text"].lower()
        if q in text:
            return line
    return None


def _eval_key(expr: str, table: dict, ctx: dict, depth: int = 0) -> float | None:
    expr = expr.strip()
    if depth > 6:
        return None
    m = re.fullmatch(r"(l\d+)\.words\[(\d+)\]\.start", expr)
    if m:
        line = _eval_line(m.group(1), table, ctx)
        if line and int(m.group(2)) < len(line["words"]):
            return line["words"][int(m.group(2))]["start"]
        return None
    m = re.fullmatch(r"(l\d+)\.(start|end)", expr)
    if m:
        line = _eval_line(m.group(1), table, ctx)
        return line[m.group(2)] if line else None
    if expr == "s0":
        return ctx["section"]["start"]
    m = re.fullmatch(r"B\(([\d.]+)\)", expr)
    if m:
        return ctx["bar"](float(m.group(1)))
    m = re.fullmatch(r"T\.section\(\"(\w+)\"\)\.(start|end)", expr)
    if m:
        sec = ctx["sections"].get(m.group(1))
        return sec[m.group(2)] if sec else None
    if re.fullmatch(r"\w+", expr) and expr in table:
        return _eval_symbol(expr, table, ctx, depth + 1)
    return None


def _eval_line(sym: str, table: dict, ctx: dict) -> dict | None:
    kind, value = table.get(sym, (None, None))
    if kind != "line":
        return None
    return _find_line(ctx["lyrics"], value)


def _eval_symbol(sym: str, table: dict, ctx: dict, depth: int = 0) -> float | None:
    kind, value = table.get(sym, (None, None))
    if kind == "expr":
        return _eval_key(str(value), table, ctx, depth)
    return None


def resolve_seconds(at: str | None, ctx: dict) -> float | None:
    """Shot time in seconds, or None when the `at` cannot be evaluated statically."""
    if not at:
        return None
    m = _CONST.search(at.strip())
    if m:
        return float(m.group(1))
    sec = re.search(r'T\.section\("(\w+)"\)\.(start|end)', at)
    if sec:
        row = ctx["sections"].get(sec.group(1))
        return row[sec.group(2)] if row else None
    ref = _KEY_REF.search(at)
    if not ref:
        return None
    sym, tail = ref.group(1), ref.group(2) or ""
    if sym in ("B", "BAR"):
        bar = re.fullmatch(r"\((\d+(?:\.\d+)?)\)", tail)
        return ctx["bar"](float(bar.group(1))) if bar else None
    if tail == "":
        if sym == "s0":
            return ctx["section"]["start"]
        return _eval_symbol(sym, ctx["table"], ctx)
    if tail in (".start", ".end"):
        expr = f"{sym}{tail}"
        m2 = re.fullmatch(r"(l\d+)\.(start|end)", expr)
        if m2:
            line = _eval_line(sym, ctx["table"], ctx)
            return line[m2.group(2)] if line else None
        return _eval_symbol(sym, ctx["table"], ctx)
    word = re.fullmatch(r"\.words\[(\d+)\]\.start", tail)
    if word:
        line = _eval_line(sym, ctx["table"], ctx)
        if line and int(word.group(1)) < len(line["words"]):
            return line["words"][int(word.group(1))]["start"]
    return None


# The read-out font is ASCII 32..126, so the film's typographic punctuation has
# to come back as its nearest plain twin or the glyph is simply missing.
CAPTION_TRANSLIT = {
    "\u00b7": ".",   # middle dot
    "\u00d7": "x",   # multiplication sign
    "\u2192": ">",
    "\u2190": "<",
    "\u2013": "-",
    "\u2014": "-",
    "\u2018": "'",
    "\u2019": "'",
    "\u201c": '"',
    "\u201d": '"',
    "\u2026": "...",
}


def normalise_caption(text: str) -> str:
    for bad, good in CAPTION_TRANSLIT.items():
        text = text.replace(bad, good)
    return "".join(c if 32 <= ord(c) <= 126 else " " for c in text)


#: Shots whose name points one way but whose `draw()` proves otherwise.
#: Keyed by (chapter, shot id); `panel` is the reason this exists at all --
#: intro's `panel` is `drawPanel` (a code panel) while c2's is
#: `instrumentPanel` (real gauges), and one keyword cannot tell them apart.
SHOT_OVERRIDES = {
    ("intro", "panel"): "glyphs",
    ("intro", "row"): "glyphs",
    ("bridge", "dialogs"): "glyphs",
    ("bridge", "dialogs2"): "glyphs",
    ("chant", "ein"): "glyphs",    # numeral 1 over a tree, not a gauge
    ("chant", "dos"): "glyphs",    # textWall
    ("chant", "trois"): "glyphs",
    # pre1 over "To A.D to B.C": the film's sky dome rewinds the year, and the
    # pen version is the ring of particles that carries the same idea.
    ("pre1", "trails"): "trails",
    ("pre1", "trailsTop"): "trailstop",
}

#: Longest first, so `dialogs` is not swallowed by `dial` and `unroll` by `roll`.
_KEYWORDS_LONGEST_FIRST = sorted(KEYWORDS, key=lambda kv: -len(kv[0]))


def motif_for(shot_id: str, chapter: str) -> str:
    override = SHOT_OVERRIDES.get((chapter, shot_id))
    if override:
        return override
    low = shot_id.lower()
    for key, motif in _KEYWORDS_LONGEST_FIRST:
        if key in low:
            return motif
    return CHAPTER_DEFAULT.get(chapter, "stars")


def param_for(shot_id: str, index: int) -> int:
    h = 0
    for ch in shot_id:
        h = (h * 31 + ord(ch)) % 97
    return (h + index * 7) % 10


def build() -> tuple[str, dict]:
    timing = json.loads((EXAMPLE / "data" / "timing.json").read_text())
    downbeats = timing["downbeats"]
    duration = timing["audio"]["duration"]
    bpm = timing["tempo"]["bpm"]
    tick_rate = bpm / 60.0 * TICKS_PER_BEAT

    sections = timing["sections"]
    chapters = read_chapters()
    pages = {c["id"]: c for c in chapters}

    beats = timing["beats"]
    lyrics = timing["lines"]
    by_id = {sec["id"]: sec for sec in sections}

    rows = []
    for sec in sections:
        page = pages.get(sec["id"])
        if not page:
            continue

        def bar(k: float, _sec=sec) -> float:
            """`B(n)` is `T.beatTime(b0 + n)` with b0 the beat the section starts on."""
            b0 = round(beat_index(beats, _sec["start"]))
            return grid_time(beats, b0 + k)

        ctx = {
            "table": page.get("keys") or {},
            "section": sec,
            "sections": by_id,
            "lyrics": lyrics,
            "bar": bar,
        }
        raw = []
        for s in page["shots"]:
            raw.append(
                {
                    "id": s["id"],
                    "t": resolve_seconds(s["at"], ctx),
                    "motif": motif_for(s["id"], sec["id"]),
                    "cap": s.get("cap", ""),
                }
            )
        # Clamp into the section and fill in whatever the bar grid could not
        # resolve, keeping the order and spacing of the ones that did.
        lo, hi = sec["start"], sec["end"]
        for r in raw:
            if r["t"] is not None:
                r["t"] = min(max(r["t"], lo), hi - 1e-3)
        known = [i for i, r in enumerate(raw) if r["t"] is not None]
        if not known or known[0] != 0:
            raw[0]["t"] = lo
            known = [0] + [i for i in known if i != 0]
        n = len(raw)
        for i, r in enumerate(raw):
            if r["t"] is not None:
                continue
            prev = max((k for k in known if k < i), default=0)
            nxt = min((k for k in known if k > i), default=None)
            if nxt is None:
                span = n - prev
                r["t"] = raw[prev]["t"] + (hi - raw[prev]["t"]) * (i - prev) / span
            else:
                span = nxt - prev
                r["t"] = raw[prev]["t"] + (raw[nxt]["t"] - raw[prev]["t"]) * (i - prev) / span
        # Strictly increasing so the timeline never has a zero-length shot.
        floor = lo
        for r in raw:
            r["t"] = max(r["t"], floor)
            floor = r["t"] + max(1.0 / tick_rate, 1e-4)
        rows.append((sec, raw))

    total_ticks = int(round(duration * tick_rate))

    # --- emit ---
    out = []
    out.append(f"public D3.totalTicks = {total_ticks};   // {duration:.2f} s at {bpm:g} BPM")
    out.append(f"public D3.tickRate = {tick_rate:.4f};      // ticks per second ({bpm:g} BPM / 16ths)")
    out.append("")
    out.append("// every section of the song, so the read-out can say where the show is")
    out.append('public D3.sectionNames = "%s";' % " ".join(s0["id"].upper() for s0 in sections))
    out.append("public D3.sections = [")
    for i, sec in enumerate(sections):
        a = int(round(sec["start"] * tick_rate))
        b = int(round(sec["end"] * tick_rate))
        comma = "," if i + 1 < len(sections) else ""   # no trailing comma
        out.append(f"    {a:>5}, {b:>5}{comma}   // {sec['id']}")
    out.append("];")
    out.append("")
    out.append("public D3.shots = [")
    key_rows = []
    yaw = 24.0
    shot_no = 0
    for sec, raw in rows:
        fade = 4 if sec["id"] in FAST else 9
        out.append(
            f"    // {sec['id']:<9} {sec['start']:>7.2f}s .. {sec['end']:>7.2f}s"
            f"  ({len(raw)} shots)"
        )
        for r in raw:
            tick = int(round(r["t"] * tick_rate))
            mid = MOTIF_ID[r["motif"]]
            par = param_for(r["id"], shot_no)
            cap = json.dumps(normalise_caption(r.get("cap", "")), ensure_ascii=False)
            out.append(f"    {tick:>5}, {mid:>2}, {fade:>2}, {par:>2}, {cap},   // {r['id']}")
            # camera key on the same tick
            yaw += 26 + (par * 9)
            pitch = 10 + (par * 4) % 34
            dist = MOTIF_DIST[r["motif"]]
            key_rows.append((tick, round(yaw, 1), pitch, dist, 3 if par % 3 else 6))
            shot_no += 1
    last = int(round(duration * tick_rate))
    out.append(f'    {last:>5},  0,  9,  0, ""    // end')
    out.append("];")
    out.append("")
    out.append("public D3.keys = [")
    for k in key_rows:
        out.append(f"    {k[0]:>5}, {k[1]:>7}, {k[2]:>3}, {k[3]:>4}, {k[4]},")
    # no trailing comma: a list literal ends at the last value
    out.append(f"    {last:>5}, {round(yaw + 26, 1):>7}, {10:>3}, {MOTIF_DIST['stars']:>4}, 3")
    out.append("];")

    block = "\n".join(out)
    stats = {
        "sections": len(rows),
        "shots": shot_no,
        "total_ticks": total_ticks,
        "motifs": len({r["motif"] for _, raw in rows for r in raw}),
    }
    return block, stats


def splice(text: str, block: str) -> str:
    start = text.find(BEGIN)
    if start < 0:
        raise SystemExit(f"missing {BEGIN!r} in anim3d/core.jsw")
    stop = text.find(END, start)
    if stop < 0:
        raise SystemExit(f"missing {END!r} in anim3d/core.jsw")
    return text[:start] + BEGIN + "\n" + block + "\n" + text[stop:]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when the block is stale")
    args = ap.parse_args(argv)

    block, stats = build()
    current = ENGINE.read_text(encoding="utf-8")
    merged = splice(current, block)
    print(
        f"sections {stats['sections']} · shots {stats['shots']} · "
        f"motifs {stats['motifs']} · {stats['total_ticks']} ticks"
    )
    if args.check:
        if merged != current:
            print("stale: anim3d/core.jsw does not match the generated data", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    if merged == current:
        print("unchanged")
        return 0
    ENGINE.write_text(merged, encoding="utf-8")
    print("wrote anim3d/core.jsw")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
