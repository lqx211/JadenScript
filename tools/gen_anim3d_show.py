"""Generate ``D3.shots`` / ``D3.keys`` for ``anim3d/core.jsw`` from wem_example's timeline.

The example webgl film registers 15 chapters, each with a list of shots whose
start is a function of the song timing. This tool reads that structure —
chapter ids, shot ids and the time each shot starts — resolves the ones written
as bar numbers against the measured downbeat grid, and lays the rest out between
them. Everything it emits is a plain data list; the visuals are ours.

Shot times come from ``wem_example/data/timing.json`` (analysis of the recording,
no audio) and the chapter/shot ids from ``wem_example/src/ch/NN_*.js``. No code
or text from the example is copied: only the running order and the clock.

    python3 tools/gen_anim3d_show.py            # rewrite the data block
    python3 tools/gen_anim3d_show.py --check    # fail when it is stale
"""

