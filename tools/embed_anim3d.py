#!/usr/bin/env python3
"""Splice the anim3d renderer into another JadenScript project.

``anim3d/core.jsw`` is written as a standalone demo: it declares its own
``Tick.tick`` and drives it from a test clock on the stage. Neither belongs in a
project that already owns that clock, so this tool copies the file with those
three things removed and fences the result between markers. Re-running replaces
the previous copy instead of appending a second one.

    python3 tools/embed_anim3d.py userspace/wem_np4_26b5/wem_np4_26b5.jsw
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_ENGINE = ROOT / "anim3d" / "core.jsw"

BEGIN = "// >>> anim3d BEGIN — generated by tools/embed_anim3d.py from anim3d/core.jsw"
END = "// <<< anim3d END"

#: Everything the standalone demo owns that a host project must supply itself.
_DROP_FEATURE = re.compile(r"^#enable_feature<[^>]*>;\s*$", re.MULTILINE)
_DROP_TICK = re.compile(r"^public D3\.tick\b.*$|^public Tick\.tick\b.*$", re.MULTILINE)
_DROP_TWCONFIG = re.compile(
    r"^metadata note Stage\b.*_twconfig_.*$\n(?:^// This metadata.*$\n)?", re.MULTILINE
)


def _drop_stage_block(text: str) -> str:
    """Remove a top-level ``stage { … }`` block, brace-counted."""
    out = []
    i = 0
    while True:
        j = text.find("stage {", i)
        if j < 0:
            out.append(text[i:])
            return "".join(out)
        # Only a block that starts at column 0 is the stage; ``stage {`` inside a
        # comment or a class body is left alone.
        line_start = text.rfind("\n", 0, j) + 1
        if text[line_start:j].strip():
            out.append(text[i : j + 7])
            i = j + 7
            continue
        out.append(text[i:j])
        depth = 0
        k = j + len("stage ")
        while k < len(text):
            ch = text[k]
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    k += 1
                    break
            k += 1
        # eat the trailing newline so we do not leave an empty line behind
        while k < len(text) and text[k] in "\r\n":
            k += 1
        i = k


def engine_block(engine: Path) -> str:
    text = engine.read_text(encoding="utf-8")
    text = _DROP_FEATURE.sub("", text)
    text = _DROP_TICK.sub("", text)
    text = _DROP_TWCONFIG.sub("", text)
    text = _drop_stage_block(text)
    text = re.sub(r"\n{3,}", "\n\n", text).strip("\n")
    return f"{BEGIN}\n{text}\n{END}\n"


def splice(target_text: str, block: str) -> str:
    start = target_text.find(BEGIN)
    if start >= 0:
        stop = target_text.find(END, start)
        if stop < 0:
            raise SystemExit(f"found {BEGIN!r} without a matching {END!r}")
        stop += len(END)
        # swallow the newline that ended the old block
        if target_text[stop : stop + 1] == "\n":
            stop += 1
        return target_text[:start] + block + target_text[stop:]
    body = target_text.rstrip("\n")
    return f"{body}\n\n{block}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("target", type=Path, help="the .jsw project to patch")
    ap.add_argument("--engine", type=Path, default=DEFAULT_ENGINE)
    ap.add_argument("--check", action="store_true", help="fail if the copy is stale")
    args = ap.parse_args(argv)

    if not args.target.exists():
        print(f"no such file: {args.target}", file=sys.stderr)
        return 2

    block = engine_block(args.engine)
    target = args.target.read_text(encoding="utf-8")
    merged = splice(target, block)

    if args.check:
        if merged != target:
            print(f"stale: {args.target} does not match {args.engine}", file=sys.stderr)
            return 1
        print(f"up to date: {args.target}")
        return 0

    if merged == target:
        print(f"unchanged: {args.target}")
        return 0
    args.target.write_text(merged, encoding="utf-8")
    added = len(merged) - len(target)
    print(f"embedded {args.engine.name} into {args.target} ({added:+d} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
