#!/usr/bin/env python3
"""A MIDI file as hex -- what the project's input box wants.

The player cannot open a file, so a song that is not compiled in has to be
pasted in as text, and the encoding is hex. Scratch compares a string to a
string by trying numbers first and then lowercasing, so ``"0"`` equals ``" "``
and ``"a"`` equals ``"A"``: Base64's 26 upper/lower pairs would collapse into
each other. Two hex digits are one byte and ``A``/``a`` mean the same thing,
which is the whole reason for the extra 50% of text.

    python3 tools/midi_to_hex.py song.mid -o build/song.hex
"""

from __future__ import annotations

import argparse
from pathlib import Path


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("midi")
    ap.add_argument("-o", "--out", help="write here instead of standard output")
    ap.add_argument("--jsw", metavar="FILE",
                    help="write a JadenScript module holding the hex as Song.hex")
    ap.add_argument("--chunk", type=int, default=60000,
                    help="characters per list item in --jsw (default 60000)")
    args = ap.parse_args(argv)
    data = Path(args.midi).expanduser().read_bytes()
    text = data.hex()
    if args.jsw:
        # The built-in song, as text, for the loader's fallback: an empty input
        # box after a paste has to play the song that was built in, and the only
        # copy of it left is this. Chunked because a quarter-megabyte string
        # literal is one token to the compiler and one block in the project.
        parts = [text[i:i + args.chunk] for i in range(0, len(text), args.chunk)] or [""]
        out = Path(args.jsw)
        out.parent.mkdir(parents=True, exist_ok=True)
        body = ",\n    ".join(f'"{part}"' for part in parts)
        out.write_text(
            "// Generated by tools/midi_to_hex.py -- do not edit.\n"
            f"// {Path(args.midi).name}: {len(data):,} bytes as hex, {len(parts)} chunks.\n\n"
            f"public Song.hex = [\n    {body}\n];\n",
            encoding="utf-8",
        )
        print(f"{args.midi}: {len(data):,} bytes -> {len(parts)} chunks -> {out}")
        return 0
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"{args.midi}: {len(data):,} bytes -> {len(text):,} hex digits -> {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
