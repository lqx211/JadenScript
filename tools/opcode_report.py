#!/usr/bin/env python3
"""Report opcode shapes from a project.json and/or the scratch-vm sources.

Usage::

    python3 tools/opcode_report.py sample_np4.26_sb3/project.json
    python3 tools/opcode_report.py --vm scratch-vm-develop
    python3 tools/opcode_report.py sample_np4.26_sb3/project.json --vm scratch-vm-develop

The first form prints, for every opcode in the project, the input slots and
fields it uses — exactly what the opcode registry in ``jswc/opcodes.py`` needs.
The second form lists every opcode the VM implements so unknown opcodes can be
spotted quickly.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_OPCODE_RE = re.compile(r"^\s+([a-z][A-Za-z0-9]*_[A-Za-z0-9_]+)\s*:", re.MULTILINE)


def project_shapes(path: Path) -> str:
    data = json.loads(path.read_text(encoding="utf-8"))
    shapes: dict[str, dict] = defaultdict(lambda: {"inputs": set(), "fields": set(), "count": 0})
    for target in data["targets"]:
        for block in target["blocks"].values():
            if not isinstance(block, dict):
                continue
            entry = shapes[block["opcode"]]
            entry["count"] += 1
            entry["inputs"].update(block.get("inputs", {}))
            entry["fields"].update(block.get("fields", {}))

    lines = [
        "<!-- Generated by tools/opcode_report.py from the reference project. -->",
        "",
        "| opcode | blocks | inputs | fields |",
        "| --- | ---: | --- | --- |",
    ]
    for opcode in sorted(shapes):
        entry = shapes[opcode]
        inputs = ", ".join(f"`{name}`" for name in sorted(entry["inputs"])) or "—"
        fields = ", ".join(f"`{name}`" for name in sorted(entry["fields"])) or "—"
        lines.append(f"| `{opcode}` | {entry['count']} | {inputs} | {fields} |")
    return "\n".join(lines)


def vm_opcodes(vm_root: Path) -> set[str]:
    opcodes: set[str] = set()
    sources = list(vm_root.glob("src/blocks/*.js"))
    sources += list(vm_root.glob("src/extensions/scratch3_music/*.js"))
    sources += list(vm_root.glob("src/extensions/scratch3_pen/*.js"))
    for source in sources:
        opcodes.update(_OPCODE_RE.findall(source.read_text(encoding="utf-8")))
    return opcodes


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project", nargs="?", help="path to a project.json")
    parser.add_argument("--vm", help="path to a scratch-vm checkout")
    parser.add_argument("--opcodes", action="store_true", help="print only VM opcode names")
    args = parser.parse_args(argv)

    if args.vm:
        opcodes = vm_opcodes(Path(args.vm))
        if args.opcodes or not args.project:
            print("\n".join(sorted(opcodes)))
    if args.project:
        print(project_shapes(Path(args.project)))
    if not args.vm and not args.project:
        parser.print_help()
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
