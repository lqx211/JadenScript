#!/usr/bin/env python3
"""Extract block metadata from TurboWarp extension sources.

The TurboWarp extension format is plain JavaScript, so a small brace-matching
parser is enough to read ``getInfo().blocks`` without executing anything.

Usage::

    python3 tools/extract_extension.py /tmp/ext_*.js        # print a report
    python3 tools/extract_extension.py --write               # refresh jswc/extension_blocks.py

Downloads happen separately (see ``EXTENSION_SOURCES`` below), because the
compiler itself must work offline.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "jswc" / "extension_blocks.py"

# extension id -> (namespace used by JadenScript, source file name in the cache)
EXTENSIONS = {
    "skyhigh173JSON": ("JSON", "ext_Skyhigh173_json.js"),
    "lmsTimers": ("Timer", "ext_Lily_MoreTimers.js"),
    "sipcconsole": ("console", "ext_-SIPC-_consoles.js"),
    "runtimeoptions": ("Runtime", "ext_runtime-options.js"),
    "utilities": ("Util", "ext_utilities.js"),
    "lmsTempVars2": ("Temp", "ext_Lily_TempVariables2.js"),
    "lmscomments": ("Comments", "ext_Lily_CommentBlocks.js"),
    "lmsMoreEvents": ("MoreEvents", "ext_Lily_MoreEvents.js"),
    "gsaWebsocket": ("WebSocket", "ext_godslayerakp_ws.js"),
}

_OPCODE_RE = re.compile(r"opcode:\s*[\"']([^\"']+)[\"']")
_BLOCKTYPE_RE = re.compile(r"blockType:\s*(?:Scratch\.)?BlockType\.(\w+)")
_ARG_RE = re.compile(
    r"^\s*([A-Za-z_$][\w$]*):\s*\{\s*type:\s*(?:Scratch\.)?ArgumentType\.(\w+)"
    r"(?:[^}]*?menu:\s*[\"']([\w$]+)[\"'])?",
    re.MULTILINE | re.DOTALL,
)


def _object_at(text: str, start: int) -> str:
    """Return the ``{...}`` object literal starting at/after ``start``."""
    open_index = text.index("{", start)
    depth = 0
    in_string = None
    i = open_index
    while i < len(text):
        ch = text[i]
        if in_string:
            if ch == "\\":
                i += 2
                continue
            if ch == in_string:
                in_string = None
        elif ch in "\"'`":
            in_string = ch
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return text[open_index : i + 1]
        i += 1
    raise ValueError("unbalanced object literal")


def extract(source: str) -> dict[str, dict]:
    """``opcode -> {type, args: [(name, argtype)]}`` for one extension source."""
    blocks: dict[str, dict] = {}
    for match in _OPCODE_RE.finditer(source):
        opcode = match.group(1)
        # ``blockType`` and ``arguments`` live in the same block object, right
        # after the opcode.
        # Only look at this block: the next ``opcode:`` starts the following
        # entry, and its ``arguments:`` must not leak into this one.
        next_opcode = _OPCODE_RE.search(source, match.end())
        stop = next_opcode.start() if next_opcode else len(source)
        window = source[match.end() : min(stop, match.end() + 4000)]
        block_type = _BLOCKTYPE_RE.search(window)
        kind = block_type.group(1) if block_type else "COMMAND"
        args: list[tuple[str, str]] = []
        if "arguments:" in window:
            arguments = _object_at(window, window.index("arguments:"))
            args = [
                (name, kind, menu or "") for name, kind, menu in _ARG_RE.findall(arguments)
            ]
        blocks[opcode] = {"type": kind, "args": args}
    return blocks


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sources", nargs="*", help="extension .js files (names from EXTENSIONS)")
    parser.add_argument("--dir", default="/tmp", help="where the downloaded sources live")
    parser.add_argument("--write", action="store_true", help=f"write {OUT.name}")
    args = parser.parse_args(argv)

    catalogue: dict[str, dict] = {}
    for extension_id, (namespace, filename) in EXTENSIONS.items():
        path = Path(args.dir) / filename
        if not path.exists():
            print(f"skip {extension_id}: {path} not found", file=sys.stderr)
            continue
        blocks = extract(path.read_text(encoding="utf-8"))
        catalogue[extension_id] = {"namespace": namespace, "blocks": blocks}

    if not args.write:
        for extension_id, entry in catalogue.items():
            print(f"{extension_id} ({entry['namespace']}): {len(entry['blocks'])} blocks")
            for opcode, spec in list(entry["blocks"].items())[:4]:
                print(f"   {opcode:28} {spec['type']:9} {spec['args']}")
        return 0

    lines = [
        '"""Generated by tools/extract_extension.py — do not edit by hand.',
        "",
        "Block metadata for the community extensions the reference projects use.",
        "Regenerate after fetching the sources from https://extensions.turbowarp.org/.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "# extension id -> {namespace, blocks: {opcode: {type, args}}}",
        "EXTENSION_BLOCKS: dict[str, dict] = {",
    ]
    for extension_id, entry in catalogue.items():
        lines.append(f'    "{extension_id}": {{')
        lines.append(f'        "namespace": "{entry["namespace"]}",')
        lines.append('        "blocks": {')
        for opcode, spec in entry["blocks"].items():
            args = ", ".join(
                f'("{name}", "{kind}", "{menu}")' for name, kind, menu in spec["args"]
            )
            lines.append(
                f'            "{opcode}": {{"type": "{spec["type"]}", "args": [{args}]}},'
            )
        lines.append("        },")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({sum(len(e['blocks']) for e in catalogue.values())} blocks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
